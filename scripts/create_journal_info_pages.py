#!/usr/bin/env python3
"""Create the three-language informational pages for a new journal.

The journal serial page remains the source of truth for the shared interface.
This command only combines that shell with editable content fragments.
"""

from __future__ import annotations

import argparse
import html
import os
import re
import subprocess
import sys
from pathlib import Path
from urllib.parse import quote


ROOT = Path(__file__).resolve().parents[1]
TEMPLATE_DIR = ROOT / "templates" / "revistas" / "nova-interface"
DEFAULT_OUTPUT = ROOT / "htdocs" / "revistas"

PAGES = {
    "p": {
        "lang": "pt",
        "about": ("paboutj.html", "Sobre o periódico"),
        "board": ("pedboard.html", "Corpo editorial"),
        "instructions": ("pinstruc.html", "Instruções aos autores"),
    },
    "e": {
        "lang": "es",
        "about": ("eaboutj.html", "Acerca del periódico"),
        "board": ("eedboard.html", "Cuerpo editorial"),
        "instructions": ("einstruc.html", "Instrucciones para los autores"),
    },
    "i": {
        "lang": "en",
        "about": ("iaboutj.html", "About the journal"),
        "board": ("iedboard.html", "Editorial board"),
        "instructions": ("iinstruc.html", "Instructions to authors"),
    },
}

LANGUAGE_PREFIX = {"pt": "p", "es": "e", "en": "i"}


def fetch(url: str) -> str:
    result = subprocess.run(
        ["curl", "-fsSL", url],
        check=False,
        text=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        timeout=60,
    )
    if result.returncode:
        raise RuntimeError(result.stderr.strip() or f"curl failed: {url}")
    return result.stdout


def replace_document_title(source: str, title: str) -> str:
    return re.sub(
        r"(?is)<title>.*?</title>",
        f"<title>{html.escape(title)}</title>",
        source,
        count=1,
    )


def add_breadcrumb_item(source: str, title: str) -> str:
    marker = '<section class="d-none d-md-flex breadcrumb'
    start = source.rfind(marker)
    if start < 0:
        raise ValueError("serial page has no modern breadcrumb")
    end = source.find("</ol>", start)
    if end < 0:
        raise ValueError("serial page breadcrumb is incomplete")
    item = f'<li class="breadcrumb-item">{html.escape(title)}</li>'
    return source[:end] + item + source[end:]


def split_serial(source: str, title: str) -> tuple[str, str]:
    content_start = source.find('<section class="journalContent')
    suffix_start = source.find('<div class="serial-template-utils"')
    if content_start < 0 or suffix_start < 0:
        raise ValueError("serial page does not contain the modern page markers")
    prefix = source[:content_start]
    suffix = source[suffix_start:]
    prefix = replace_document_title(prefix, title)
    prefix = add_breadcrumb_item(prefix, title)
    return prefix, suffix


def build_content(content: str, title: str) -> str:
    return f'''<!-- generated by scripts/create_journal_info_pages.py; edit only the content below -->
<section class="journalContent journal-about-section mb-5">
  <div class="container">
    <div class="row">
      <div class="col-12 col-lg-8">
        <h2 class="scielo__text-title--4" id="about">{html.escape(title)}</h2>
        <div class="journal-about-legacy">
{content.rstrip()}
        </div>
      </div>
    </div>
  </div>
</section>
'''


def render_page(serial: str, content: str, title: str) -> str:
    prefix, suffix = split_serial(serial, title)
    return prefix + build_content(content, title) + suffix


def validate_acronym(value: str) -> str:
    if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9._-]{1,63}", value):
        raise argparse.ArgumentTypeError(
            "acronym must contain 2-64 letters, numbers, dots, underscores or hyphens"
        )
    return value


def validate_issn(value: str) -> str:
    if not re.fullmatch(r"[0-9]{4}-[0-9Xx]{4}", value):
        raise argparse.ArgumentTypeError("issn must use the format 0000-0000")
    return value.upper()


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(
        description="Generate blank informational pages using the modern journal shell."
    )
    parser.add_argument("--acronym", required=True, type=validate_acronym)
    parser.add_argument("--issn", required=True, type=validate_issn)
    parser.add_argument(
        "--base-url",
        default=os.environ.get("SERVER_SCIELO", "http://127.0.0.1:8090"),
        help="running Educ@ URL used to obtain the shared journal shell",
    )
    parser.add_argument(
        "--output-root",
        type=Path,
        default=DEFAULT_OUTPUT,
        help="directory containing the journal folders",
    )
    parser.add_argument(
        "--force",
        action="store_true",
        help="replace an existing informational-page directory",
    )
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    output_dir = args.output_root / args.acronym
    existing_pages = [
        output_dir / filename
        for language in PAGES.values()
        for kind in ("about", "board", "instructions")
        for filename in [
            {
                "about": f"{LANGUAGE_PREFIX[language['lang']]}aboutj.htm",
                "board": f"{LANGUAGE_PREFIX[language['lang']]}edboard.htm",
                "instructions": f"{LANGUAGE_PREFIX[language['lang']]}instruc.htm",
            }[kind]
        ]
    ]
    if output_dir.exists() and any(path.exists() for path in existing_pages) and not args.force:
        print(
            f"Refusing to overwrite existing pages in {output_dir}. Use --force only after backup.",
            file=sys.stderr,
        )
        return 2

    output_dir.mkdir(parents=True, exist_ok=True)
    for language in PAGES.values():
        serial_url = (
            f"{args.base_url.rstrip('/')}/scielo.php?script=sci_serial"
            f"&pid={quote(args.issn)}&lng={language['lang']}&nrm=iso"
        )
        serial = fetch(serial_url)
        for kind, (template_name, title) in language.items():
            if kind == "lang":
                continue
            template = TEMPLATE_DIR / template_name
            if not template.is_file():
                raise FileNotFoundError(template)
            prefix = LANGUAGE_PREFIX[language["lang"]]
            target_name = {
                "about": f"{prefix}aboutj.htm",
                "board": f"{prefix}edboard.htm",
                "instructions": f"{prefix}instruc.htm",
            }[kind]
            target = output_dir / target_name
            target.write_text(
                render_page(serial, template.read_text(encoding="utf-8"), title),
                encoding="utf-8",
            )
            print(target)

    print("\nNext steps:")
    print(f"1. Put glogo.gif and plogo.gif in htdocs/img/revistas/{args.acronym}/.")
    print(f"2. Replace the EDITOR markers in {output_dir}/*.htm.")
    print("3. Validate the three languages before publishing.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
